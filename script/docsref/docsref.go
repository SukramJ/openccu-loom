// Package docsref renders the generated reference pages under
// docs/reference/ from the sources they describe: the config schema the
// REST API serves, the WebSocket catalogue in assets/wsapi.json and the
// OpenAPI document in assets/openapi.yaml. The pages are checked in; a
// contract test regenerates them and fails when the copy on disk is stale,
// so the published reference cannot drift from the code.
package docsref

import (
	"fmt"
	"strings"
)

// Repository-relative paths of the generated pages.
const (
	ConfigurationPage = "docs/reference/configuration.md"
	WebSocketPage     = "docs/reference/websocket.md"
	RESTPage          = "docs/reference/rest.md"
)

// Pages renders every generated reference page. root is the repository
// root; the result is keyed by repository-relative, slash-separated path.
// The output is deterministic: the same sources yield the same bytes.
func Pages(root string) (map[string][]byte, error) {
	cfg, err := configurationPage(root)
	if err != nil {
		return nil, err
	}
	ws, err := websocketPage(root)
	if err != nil {
		return nil, err
	}
	rest, err := restPage(root)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		ConfigurationPage: cfg,
		WebSocketPage:     ws,
		RESTPage:          rest,
	}, nil
}

// generatedMarker is the comment every page carries under its title.
func generatedMarker(source string) string {
	return fmt.Sprintf("<!-- Generated by `make docs-reference` from %s. Do not edit by hand. -->\n", source)
}

// anchor turns a dotted key into a stable heading id.
func anchor(prefix, key string) string {
	r := strings.NewReplacer(".", "-", "_", "-", "/", "-", " ", "-")
	id := strings.ToLower(r.Replace(key))
	if prefix != "" {
		id = prefix + "-" + id
	}
	return id
}

// anchors hands out heading ids that are unique within one page; two
// keys that differ only in case or punctuation get a numeric suffix in
// the order they are rendered.
type anchors map[string]bool

func (a anchors) next(prefix, key string) string {
	id := anchor(prefix, key)
	out := id
	for n := 2; a[out]; n++ {
		out = fmt.Sprintf("%s-%d", id, n)
	}
	a[out] = true
	return out
}

// cell makes a value safe for one Markdown table cell. Newlines collapse
// to spaces and pipes are escaped everywhere. Outside code spans the
// characters Markdown would read as HTML or emphasis are escaped too, so
// a help text such as `<topic_base>/status/...` renders literally.
func cell(s string) string {
	s = strings.Join(strings.Fields(strings.NewReplacer("\r\n", " ", "\n", " ", "\r", " ").Replace(s)), " ")
	var b strings.Builder
	inCode := false
	for i := range len(s) {
		c := s[i]
		switch {
		case c == '`':
			// Only open a code span that is closed later on; a stray
			// backtick stays a literal character.
			if inCode || strings.IndexByte(s[i+1:], '`') >= 0 {
				inCode = !inCode
				b.WriteByte(c)
			} else {
				b.WriteString("\\`")
			}
		case c == '|':
			b.WriteString("\\|")
		case inCode:
			b.WriteByte(c)
		case c == '<':
			b.WriteString("&lt;")
		case c == '>':
			b.WriteString("&gt;")
		case c == '*':
			b.WriteString("\\*")
		default:
			b.WriteByte(c)
		}
	}
	return b.String()
}

// code renders s as an inline code span inside a table cell.
func code(s string) string {
	if s == "" {
		return ""
	}
	s = strings.Join(strings.Fields(s), " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	fence := "`"
	for strings.Contains(s, fence) {
		fence += "`"
	}
	if len(fence) > 1 || strings.HasPrefix(s, "`") || strings.HasSuffix(s, "`") {
		return fence + " " + s + " " + fence
	}
	return fence + s + fence
}

// table writes a Markdown table with the given header and rows.
func table(b *strings.Builder, header []string, rows [][]string) {
	b.WriteString("| " + strings.Join(header, " | ") + " |\n")
	sep := make([]string, len(header))
	for i := range sep {
		sep[i] = "---"
	}
	b.WriteString("|" + strings.Join(sep, "|") + "|\n")
	for _, r := range rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
}
