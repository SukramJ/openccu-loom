func TestCellEscapesOutsideCodeSpans(t *testing.T) {
	cases := map[string]string{
		"a | b":                     `a \| b`,
		"line\nbreak":               "line break",
		"<topic_base>/status":       "&lt;topic_base&gt;/status",
		"keep `<x> | y` raw":        "keep `<x> \\| y` raw",
		"use [\"*\"] only":          `use ["\*"] only`,
		"stray ` tick":              "stray \\` tick",
		"  spaced\t\tout  ":         "spaced out",
		"`a` then <b> and `c*d` ok": "`a` then &lt;b&gt; and `c*d` ok",
	}
	for in, want := range cases {
		if got := cell(in); got != want {
			t.Errorf("cell(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestCodeWidensTheFenceAroundBackticks(t *testing.T) {
	if got := code("a`b"); got != "`` a`b ``" {
		t.Errorf("code = %q", got)
	}
	if got := code(""); got != "" {
		t.Errorf("code(\"\") = %q, want empty", got)
	}
	if got := code("x|y"); got != "`x\\|y`" {
		t.Errorf("code = %q", got)
	}
}

func TestAccessOfClassifiesTheEffectiveSecurity(t *testing.T) {
	global := openapi3.SecurityRequirements{
		{"basicAuth": {}},
		{"openIdConnect": {"viewer"}},
	}
	none := openapi3.SecurityRequirements{}
	admin := openapi3.SecurityRequirements{{"basicAuth": {}}, {"openIdConnect": {"admin"}}}
	anyone := openapi3.SecurityRequirements{{"basicAuth": {}}, {"openIdConnect": {}}}
	cases := []struct {
		name string
		op   *openapi3.Operation
		want string
	}{
		{"inherits the document default", &openapi3.Operation{}, "viewer"},
		{"empty list is public", &openapi3.Operation{Security: &none}, "public"},
		{"scope names the role", &openapi3.Operation{Security: &admin}, "admin"},
		{"no scope is authenticated", &openapi3.Operation{Security: &anyone}, "authenticated"},
	}
	for _, c := range cases {
		if got := accessOf(c.op, global); got != c.want {
			t.Errorf("%s: got %q, want %q", c.name, got, c.want)
		}
	}
}

func TestAnchorsStayUniqueWithinAPage(t *testing.T) {
	ids := anchors{}
	if a, b := ids.next("", "System"), ids.next("", "system"); a != "system" || b != "system-2" {
		t.Fatalf("got %q, %q", a, b)
	}
}

func TestRenderArgsKeepsDeclarationOrder(t *testing.T) {
	got, err := renderArgs([]byte(`{"id":"string","central_name":"string?"}`))
	if err != nil || got != "id: string, central_name: string?" {
		t.Fatalf("renderArgs = %q, %v", got, err)
	}
	if got, err := renderArgs(nil); err != nil || got != "" {
		t.Fatalf("renderArgs(nil) = %q, %v", got, err)
	}
}

func TestPagesAreDeterministicAndMarked(t *testing.T) {
	root := filepath.Join("..", "..")
	first, err := Pages(root)
	if err != nil {
		t.Fatalf("Pages: %v", err)
	}
	second, err := Pages(root)
	if err != nil {
		t.Fatalf("Pages: %v", err)
	}
	for _, p := range []string{ConfigurationPage, WebSocketPage, RESTPage} {
		if !bytes.Equal(first[p], second[p]) {
			t.Errorf("%s differs between two renders", p)
		}
		if !strings.Contains(string(first[p]), "<!-- Generated by `make docs-reference` from ") {
			t.Errorf("%s lacks the generated marker", p)
		}
	}
}
