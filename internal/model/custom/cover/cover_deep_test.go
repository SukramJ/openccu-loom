// TestCoverIsStateChangeFirstCommandAlwaysTrue verifies that IsStateChange
// returns true when no position has been observed yet (first command always
// goes through), and false when the observed position matches the target.
func TestCoverIsStateChangeFirstCommandAlwaysTrue(t *testing.T) {
	t.Parallel()

	c, _, level := newRig(t, "x", &stubWriter{}, custom.CoverCapabilities{})

	// No position observed → must indicate state change.
	if !c.IsStateChange(0.5) {
		t.Error("IsStateChange must return true when position is not yet observed")
	}

	level.OnEvent(0.5)
	// Same target as current → no state change.
	if c.IsStateChange(0.5) {
		t.Error("IsStateChange must return false when target equals current position")
	}
	// Different target → state change.
	if !c.IsStateChange(0.8) {
		t.Error("IsStateChange must return true when target differs from current position")
	}
}

