// --- Cover deep tests ---

// TestCoverConstructFromChannelWithLevelDP verifies that a Cover built from a
// channel that carries a LEVEL data point has a non-nil Float and can read the
// position.
func TestCoverConstructFromChannelWithLevelDP(t *testing.T) {
	t.Parallel()

	w := &stubWriter{}
	c, _, level := newRig(t, "HmIP-BROLL:3", w, custom.CoverCapabilities{})

	if c.Float == nil {
		t.Fatal("Cover.Float must not be nil when channel carries LEVEL DP")
	}

	// Not observed yet.
	if _, ok := c.Position(); ok {
		t.Error("Position() must not be observed before any event")
	}

	level.OnEvent(0.6)
	pos, ok := c.Position()
	if !ok {
		t.Fatal("Position() must be observed after OnEvent")
	}
	if pos.Level() != 0.6 {
		t.Errorf("Position().Level() = %v, want 0.6", pos.Level())
	}
}

// TestCoverNilLevelDPGracefullyDegrades verifies that a Cover constructed from
// a channel without a LEVEL DP does not panic and returns safe values.
func TestCoverNilLevelDPGracefullyDegrades(t *testing.T) {
	t.Parallel()

	d := device.New(device.Config{InterfaceID: "HmIP-RF", Address: "ABC0001"})
	// Channel with no LEVEL DP.
	ch := d.AddChannel("HmIP-BROLL:3", 1, "BLIND", hmenum.ParamsetKeyValues)
	c := New(Config{Channel: ch, Writer: &stubWriter{}, Capabilities: custom.CoverCapabilities{}})

	if c.Float != nil {
		t.Error("Cover.Float must be nil when channel has no LEVEL DP")
	}
	if _, ok := c.Position(); ok {
		t.Error("Position() must not be observed when LEVEL DP is absent")
	}
	// Write attempts must error cleanly.
	if err := c.SetPosition(context.Background(), 0.5, hmenum.CommandPriorityHigh); err == nil {
		t.Error("SetPosition must return an error when LEVEL DP is absent")
	}
	// DataPointKey must NOT panic when Float is nil — the autogenerated
	// forwarder previously dispatched to (*DataPoint).DataPointKey on a
	// nil receiver and crashed the daemon during materialisation.
	if got := c.DataPointKey(); got != (hmtypes.DataPointKey{}) {
		t.Errorf("DataPointKey() with nil Float = %v, want zero key", got)
	}
	// Same hazard, different forwarder: Category dispatches through
	// (*DataPoint).Category which dereferences its receiver. The WS
	// custom-DP-list handler hit this on a half-formed Cover.
	if got := c.Category(); got != hmenum.DataPointCategoryUndefined {
		t.Errorf("Category() with nil Float = %v, want undefined", got)
	}
}

