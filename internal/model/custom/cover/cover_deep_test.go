// fireDoorState resolves label against dp's own VALUE_LIST and fires the
// resulting raw index as a wire event — mirrors how the resolver projects the
// read-only ENUM parameter DOOR_STATE onto an index-valued Sensor[int32].
func fireDoorState(t *testing.T, dp *generic.Sensor[int32], label string) {
	t.Helper()
	idx, ok := custom.EnumLabelIndex(dp, label)
	if !ok {
		t.Fatalf("label %q not in VALUE_LIST", label)
	}
	dp.OnEvent(idx)
}

// newGarageRig builds a channel carrying DOOR_STATE and SECTION data points
// and returns a Garage against it.
//
//nolint:gocritic // test rig helper — positional returns are the test convention
func newGarageRig(t *testing.T, address string, w Writer) (*Garage, *generic.Sensor[int32], *generic.Sensor[int32]) {
	t.Helper()
	d := device.New(device.Config{InterfaceID: "HmIP-RF", Address: "ABC0001"})
	ch := d.AddChannel(address, 1, "GARAGE_DOOR", hmenum.ParamsetKeyValues)

	doorState := generic.NewIntegerSensor(generic.Spec{
		Key: hmtypes.DataPointKey{
			ChannelAddress: address,
			ParamsetKey:    hmenum.ParamsetKeyValues,
			Parameter:      string(hmenum.ParameterDoorState),
		},
		Descriptor: hmproto.ParameterData{
			Type:       hmenum.ParameterTypeEnum,
			Operations: hmenum.OperationsRead | hmenum.OperationsEvent,
			ValueList:  []string{"UNKNOWN", "OPEN", "CLOSED", "VENTILATION_POSITION"},
		},
	})
	section := generic.NewIntegerSensor(generic.Spec{
		Key: hmtypes.DataPointKey{
			ChannelAddress: address,
			ParamsetKey:    hmenum.ParamsetKeyValues,
			Parameter:      string(hmenum.ParameterSection),
		},
		Descriptor: hmproto.ParameterData{
			Type:       hmenum.ParameterTypeInteger,
			Operations: hmenum.OperationsRead | hmenum.OperationsEvent,
		},
	})
	ch.Put(doorState)
	ch.Put(section)

	g := NewGarage(GarageConfig{Channel: ch, Writer: w, Capabilities: custom.CoverCapabilities{}})
	// Deferred GoTo*Percentage writes fire only via flushGoToWrites so
	// tests stay deterministic.
	neuterGoToTimers(&g.matterGoTo)
	return g, doorState, section
}

// TestGaragePositionDerivesFromDoorState verifies the virtual-position
// mapping: OPEN→1.0, VENTILATION→0.5, CLOSED→0.0.
func TestGaragePositionDerivesFromDoorState(t *testing.T) {
	t.Parallel()

	g, _, _ := newGarageRig(t, "HmIP-MOD-HO:1", &stubWriter{})

	// No state observed yet.
	if _, ok := g.Position(); ok {
		t.Error("Position() must not be observed before any state event")
	}

	cases := []struct {
		state      DoorState
		wantPos    float64
		wantClosed bool
	}{
		{DoorStateOpen, 1.0, false},
		{DoorStateVentilation, 0.5, false},
		{DoorStateClosed, 0.0, true},
	}
	for _, tc := range cases {
		g.OnState(tc.state)
		pos, ok := g.Position()
		if !ok {
			t.Errorf("state=%s: Position() not observed", tc.state)
			continue
		}
		if pos.Level() != tc.wantPos {
			t.Errorf("state=%s: Position().Level() = %v, want %v", tc.state, pos.Level(), tc.wantPos)
		}
		if got := g.IsClosed(); got != tc.wantClosed {
			t.Errorf("state=%s: IsClosed() = %v, want %v", tc.state, got, tc.wantClosed)
		}
	}
}

