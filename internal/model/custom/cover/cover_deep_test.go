// TestGarageSetPositionMapsToCommand verifies the three threshold bands of
// SetPosition: >=0.75→OPEN, 0.25..0.75→PARTIAL_OPEN, <0.25→CLOSE.
func TestGarageSetPositionMapsToCommand(t *testing.T) {
	t.Parallel()

	cases := []struct {
		target  float64
		wantCmd DoorCommand
	}{
		{1.0, DoorCommandOpen},
		{0.75, DoorCommandOpen},
		{0.5, DoorCommandPartialOpen},
		{0.25, DoorCommandPartialOpen},
		{0.1, DoorCommandClose},
		{0.0, DoorCommandClose},
	}

	for _, tc := range cases {
		w := &stubWriter{}
		g, _, _ := newGarageRig(t, "HmIP-MOD-HO:1", w)
		if err := g.SetPosition(context.Background(), tc.target, hmenum.CommandPriorityHigh); err != nil {
			t.Errorf("SetPosition(%v) error: %v", tc.target, err)
			continue
		}
		if w.last.(string) != string(tc.wantCmd) {
			t.Errorf("SetPosition(%v) sent %v, want %v", tc.target, w.last, tc.wantCmd)
		}
	}
}
