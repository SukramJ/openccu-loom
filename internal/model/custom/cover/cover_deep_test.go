// TestBlindTiltPositionReflectsLevel2 verifies that TiltPosition() returns
// the value written to LEVEL_2 via OnEvent on the underlying generic.Float.
func TestBlindTiltPositionReflectsLevel2(t *testing.T) {
	t.Parallel()

	w := &putWriter{}
	d := device.New(device.Config{InterfaceID: "HmIP-RF", Address: "ABC0001"})
	ch := d.AddChannel("VCU3560967:1", 1, "BLIND", hmenum.ParamsetKeyValues)

	mk := func(p hmenum.Parameter) *generic.Float {
		return generic.NewFloat(generic.Spec{
			Key: hmtypes.DataPointKey{
				ChannelAddress: "VCU3560967:1",
				ParamsetKey:    hmenum.ParamsetKeyValues,
				Parameter:      string(p),
			},
			Descriptor: hmproto.ParameterData{
				Type:       hmenum.ParameterTypeFloat,
				Operations: hmenum.OperationsRead | hmenum.OperationsWrite | hmenum.OperationsEvent,
			},
			Writer: w,
		})
	}
	level := mk(hmenum.ParameterLevel)
	level2 := mk(hmenum.ParameterLevel2)
	ch.Put(level)
	ch.Put(level2)

	b := NewBlind(BlindConfig{Channel: ch, Writer: w, Capabilities: custom.CoverCapabilities{SupportsTilt: true}, Kind: BlindKindHM})

	// No tilt observed yet.
	if _, ok := b.TiltPosition(); ok {
		t.Error("TiltPosition() must not be observed before any event")
	}

	// Push a value via the shared LEVEL_2 pointer.
	level2.OnEvent(0.3)
	pos, ok := b.TiltPosition()
	if !ok {
		t.Fatal("TiltPosition() must be observed after level2 OnEvent")
	}
	if pos.Level() != 0.3 {
		t.Errorf("TiltPosition().Level() = %v, want 0.3", pos.Level())
	}
}

// TestBlindOpenTiltSetsLevel2ToMax verifies OpenTilt() → LEVEL_COMBINED encodes
// tilt=1.0 (200/0xc8) in the second hex octet of the HM wire string.
func TestBlindOpenTiltSetsLevel2ToMax(t *testing.T) {
	t.Parallel()

	w := &putWriter{}
	b := newBlindRig(t, "VCU3560967:1", w, custom.CoverCapabilities{SupportsTilt: true}, BlindKindHM)

	if err := b.OpenTilt(context.Background(), hmenum.CommandPriorityHigh); err != nil {
		t.Fatal(err)
	}
	cc := w.combinedCalls()
	if len(cc) == 0 {
		t.Fatal("OpenTilt must produce at least one LEVEL_COMBINED SetValue")
	}
	got, ok := cc[len(cc)-1].value.(string)
	if !ok {
		t.Fatalf("LEVEL_COMBINED value type = %T, want string", cc[len(cc)-1].value)
	}
	// tilt=1.0 → int(1.0*100*2)=200=0xc8; level=0 → 0x00 → "0x00,0xc8"
	if got != "0x00,0xc8" {
		t.Errorf("OpenTilt: LEVEL_COMBINED = %q, want 0x00,0xc8", got)
	}
}

